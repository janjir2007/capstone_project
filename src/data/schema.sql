-- =====================================================================
-- Oil Change Predictor — PostgreSQL schema (Task 1.1)
-- Structure: companies -> vehicles -> service_records
--            vehicles  -> predictions -> reminders
-- Column meanings: docs/data_dictionary.md
--
-- Rules followed:
--   D-004  driver name + phone stored per service record, not per vehicle
--   D-005  vehicle identifier_type is 'plate' or 'fleet_no'
--   D-006  (PROPOSED) prediction target is days to next change
--   D-007  (PROPOSED) at risk = predicted date + 7 days grace passed, no return
--   D-010  (PROPOSED) reminders are generated and marked 'sent' manually
--   Service count and segments are COMPUTED (view + function), never stored.
--
-- No schema name is hard-coded: objects are created in the current
-- search_path (normally "public"). The tests rely on this.
-- =====================================================================

-- ---------------------------------------------------------------------
-- companies: the customer (fleet owner). A private truck owner is also
-- stored here, as a company row named after the owner.
-- ---------------------------------------------------------------------
CREATE TABLE companies (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT        NOT NULL UNIQUE CHECK (btrim(name) <> ''),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- vehicles: one truck. Identified by a licence plate or, for mine haul
-- trucks without plates, a company fleet number.
-- ---------------------------------------------------------------------
CREATE TABLE vehicles (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id        BIGINT      NOT NULL REFERENCES companies (id),
    identifier_type   TEXT        NOT NULL CHECK (identifier_type IN ('plate', 'fleet_no')),
    identifier        TEXT        NOT NULL CHECK (btrim(identifier) <> ''),
    -- Filled by src/common/plates.py (the ONLY place plates are normalized).
    -- No format CHECK yet: real plate letters are unverified (open question 7).
    plate_normalized  TEXT,
    vehicle_model     TEXT,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- A plate vehicle must have a normalized plate; a fleet vehicle must not.
    CONSTRAINT vehicles_plate_matches_type CHECK (
        (identifier_type = 'plate'    AND plate_normalized IS NOT NULL)
     OR (identifier_type = 'fleet_no' AND plate_normalized IS NULL)
    )
);

-- One vehicle per plate across the whole database (NULLs are not compared).
CREATE UNIQUE INDEX vehicles_plate_normalized_uq ON vehicles (plate_normalized);
-- Fleet numbers are only unique inside one company ("HT-12" can exist twice).
CREATE UNIQUE INDEX vehicles_fleet_no_per_company_uq
    ON vehicles (company_id, identifier) WHERE identifier_type = 'fleet_no';
CREATE INDEX vehicles_company_id_idx ON vehicles (company_id);

-- ---------------------------------------------------------------------
-- service_records: one oil change. Driver and phone live here (D-004).
-- ---------------------------------------------------------------------
CREATE TABLE service_records (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id    BIGINT        NOT NULL REFERENCES vehicles (id),
    service_date  DATE          NOT NULL,
    odometer_km   INTEGER       CHECK (odometer_km >= 0),
    engine_hours  NUMERIC(8, 1) CHECK (engine_hours >= 0),
    oil_grade     TEXT          NOT NULL CHECK (btrim(oil_grade) <> ''),
    liters        NUMERIC(5, 1) NOT NULL CHECK (liters > 0),
    route         TEXT          CHECK (route IN ('ub_city', 'mn_china', 'mn_russia', 'mine_site', 'mixed')),
    driver_name   TEXT,
    -- Mongolian number, 8 digits, no +976 and no spaces (normalized before insert).
    driver_phone  TEXT          CHECK (driver_phone ~ '^[0-9]{8}$'),
    oil_changer   TEXT,
    -- Reference to a stored photo (Supabase Storage key / path), never the image.
    photo_ref     TEXT,
    created_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    -- Mine trucks may track engine hours instead of km; at least one is needed.
    CONSTRAINT service_records_has_meter CHECK (odometer_km IS NOT NULL OR engine_hours IS NOT NULL),
    -- Lets predictions check that their service belongs to the same vehicle.
    CONSTRAINT service_records_id_vehicle_uq UNIQUE (id, vehicle_id)
);

CREATE INDEX service_records_vehicle_date_idx ON service_records (vehicle_id, service_date);
CREATE INDEX service_records_driver_phone_idx ON service_records (driver_phone);

-- ---------------------------------------------------------------------
-- predictions: model output for a vehicle, made after one service record.
-- days_left and status (OK / due soon / overdue) are computed at read time.
-- ---------------------------------------------------------------------
CREATE TABLE predictions (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id           BIGINT        NOT NULL REFERENCES vehicles (id),
    based_on_service_id  BIGINT        NOT NULL,
    predicted_days       NUMERIC(6, 1) NOT NULL CHECK (predicted_days >= 0),
    predicted_date       DATE          NOT NULL,
    model_version        TEXT          NOT NULL CHECK (btrim(model_version) <> ''),
    created_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    -- The service must belong to the same vehicle as the prediction.
    CONSTRAINT predictions_service_same_vehicle_fk
        FOREIGN KEY (based_on_service_id, vehicle_id)
        REFERENCES service_records (id, vehicle_id),
    CONSTRAINT predictions_id_vehicle_uq UNIQUE (id, vehicle_id)
);

CREATE INDEX predictions_vehicle_id_idx ON predictions (vehicle_id);

-- ---------------------------------------------------------------------
-- reminders: Mongolian reminder message for one prediction (D-010).
-- ---------------------------------------------------------------------
CREATE TABLE reminders (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id     BIGINT      NOT NULL REFERENCES vehicles (id),
    prediction_id  BIGINT      NOT NULL,
    phone          TEXT        NOT NULL CHECK (phone ~ '^[0-9]{8}$'),
    message_text   TEXT        NOT NULL CHECK (btrim(message_text) <> ''),
    status         TEXT        NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'sent')),
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    sent_at        TIMESTAMPTZ,
    -- sent_at is filled exactly when status is 'sent'.
    CONSTRAINT reminders_sent_at_matches_status CHECK ((status = 'sent') = (sent_at IS NOT NULL)),
    -- The prediction must belong to the same vehicle as the reminder.
    CONSTRAINT reminders_prediction_same_vehicle_fk
        FOREIGN KEY (prediction_id, vehicle_id)
        REFERENCES predictions (id, vehicle_id)
);

CREATE INDEX reminders_vehicle_id_idx ON reminders (vehicle_id);
CREATE INDEX reminders_status_idx ON reminders (status);

-- =====================================================================
-- COMPUTED VALUES (not stored)
-- =====================================================================

-- ---------------------------------------------------------------------
-- v_vehicle_service_summary: service count + the latest service's fields
-- (used to pre-fill the form and to show the vehicle card).
-- ---------------------------------------------------------------------
CREATE VIEW v_vehicle_service_summary AS
WITH counts AS (
    SELECT vehicle_id,
           COUNT(*)          AS service_count,
           MIN(service_date) AS first_service_date,
           MAX(service_date) AS last_service_date
    FROM service_records
    GROUP BY vehicle_id
),
latest AS (
    -- DISTINCT ON keeps the first row per vehicle in the ORDER BY order,
    -- i.e. the newest service (id breaks ties on the same day).
    SELECT DISTINCT ON (vehicle_id)
           vehicle_id, id AS last_service_id, odometer_km, engine_hours,
           oil_grade, liters, route, driver_name, driver_phone
    FROM service_records
    ORDER BY vehicle_id, service_date DESC, id DESC
)
SELECT c.vehicle_id,
       c.service_count,
       c.first_service_date,
       c.last_service_date,
       l.last_service_id,
       l.odometer_km   AS last_odometer_km,
       l.engine_hours  AS last_engine_hours,
       l.oil_grade     AS last_oil_grade,
       l.liters        AS last_liters,
       l.route         AS last_route,
       l.driver_name   AS last_driver_name,
       l.driver_phone  AS last_driver_phone
FROM counts c
JOIN latest l ON l.vehicle_id = c.vehicle_id;

-- ---------------------------------------------------------------------
-- vehicle_segments(as_of, grace_days): segment of every vehicle that has
-- at least one service on or before as_of.
--   at_risk   : latest prediction's date + grace_days < as_of AND no service
--               after the service that prediction was based on  (D-007)
--   new       : 1 service
--   returning : 2 services
--   loyal     : 3+ services
-- at_risk wins over the count-based segments.
-- as_of is a parameter so results are reproducible (tests, "time travel").
-- ---------------------------------------------------------------------
CREATE FUNCTION vehicle_segments(as_of DATE DEFAULT CURRENT_DATE, grace_days INTEGER DEFAULT 7)
RETURNS TABLE (
    vehicle_id             BIGINT,
    service_count          BIGINT,
    last_service_date      DATE,
    latest_predicted_date  DATE,
    segment                TEXT
)
LANGUAGE sql
STABLE
AS $$
    WITH svc AS (
        SELECT sr.vehicle_id,
               COUNT(*)             AS service_count,
               MAX(sr.service_date) AS last_service_date
        FROM service_records sr
        WHERE sr.service_date <= as_of
        GROUP BY sr.vehicle_id
    ),
    latest_pred AS (
        -- Newest prediction per vehicle, only if its service existed by as_of.
        SELECT DISTINCT ON (p.vehicle_id)
               p.vehicle_id,
               p.predicted_date,
               base.service_date AS based_on_date
        FROM predictions p
        JOIN service_records base ON base.id = p.based_on_service_id
        WHERE base.service_date <= as_of
        ORDER BY p.vehicle_id, base.service_date DESC, p.created_at DESC, p.id DESC
    )
    SELECT s.vehicle_id,
           s.service_count,
           s.last_service_date,
           lp.predicted_date,
           CASE
               WHEN lp.predicted_date IS NOT NULL
                AND lp.predicted_date + grace_days < as_of
                AND s.last_service_date <= lp.based_on_date THEN 'at_risk'
               WHEN s.service_count = 1 THEN 'new'
               WHEN s.service_count = 2 THEN 'returning'
               ELSE 'loyal'
           END
    FROM svc s
    LEFT JOIN latest_pred lp ON lp.vehicle_id = s.vehicle_id;
$$;

-- Today's segments (what the app and GET /stats/segments would use).
CREATE VIEW v_vehicle_segment AS
SELECT * FROM vehicle_segments(CURRENT_DATE);
