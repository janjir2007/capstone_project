CREATE TABLE reminders_sent (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id      BIGINT      NOT NULL REFERENCES vehicles (id),
    -- The vehicle's newest service when the reminder was sent.
    service_id      BIGINT      NOT NULL,
    -- Recipient (driver phone of that service); NULL = there was no phone, reminded another way.
    phone           TEXT        CHECK (phone ~ '^[0-9]{8}$'),
    -- The exact Mongolian text that went out (wording may change later; this is what was sent).
    message_text    TEXT        NOT NULL CHECK (btrim(message_text) <> ''),
    -- What the reminder was based on (for checking reminder timing later, D-036).
    method          TEXT        NOT NULL CHECK (method IN ('ridge', 'b1', 'b0')),
    model_version   TEXT        NOT NULL CHECK (btrim(model_version) <> ''),
    predicted_date  DATE        NOT NULL,
    send_on         DATE        NOT NULL,
    sent_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- The service must belong to the same vehicle.
    CONSTRAINT reminders_sent_service_same_vehicle_fk
        FOREIGN KEY (service_id, vehicle_id)
        REFERENCES service_records (id, vehicle_id),
    -- Marking twice must not create a second row (POST /reminders/{id}/sent is idempotent).
    CONSTRAINT reminders_sent_one_per_service_uq UNIQUE (service_id)
);

CREATE INDEX reminders_sent_vehicle_id_idx ON reminders_sent (vehicle_id);
