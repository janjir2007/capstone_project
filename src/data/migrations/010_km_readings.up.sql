-- ---------------------------------------------------------------- 1. target per service

ALTER TABLE service_records
    ADD COLUMN interval_km INTEGER CHECK (interval_km > 0),
    ADD COLUMN target_km   INTEGER,
    -- Both or none; IS NOT NULL spelled out: a CHECK that is NULL (e.g. target = odometer + NULL) passes.
    ADD CONSTRAINT service_records_target_km_check CHECK (
        (interval_km IS NULL AND target_km IS NULL)
        OR (odometer_km IS NOT NULL AND interval_km IS NOT NULL AND target_km IS NOT NULL
            AND target_km = odometer_km + interval_km));

UPDATE service_records
SET interval_km = 15000, target_km = odometer_km + 15000
WHERE odometer_km IS NOT NULL;

-- ---------------------------------------------------------------- 2. readings

CREATE TABLE odometer_readings (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id    BIGINT        NOT NULL REFERENCES vehicles (id),
    service_id    BIGINT        NOT NULL,
    unit          TEXT          NOT NULL CHECK (unit IN ('km', 'hours')),
    value         NUMERIC(9, 1) NOT NULL CHECK (value >= 0),
    reading_date  DATE          NOT NULL,
    source        TEXT          NOT NULL CHECK (source IN ('service', 'manual', 'messenger')),
    status        TEXT          NOT NULL CHECK (status IN ('ok', 'flagged')),
    flag_reason   TEXT          CHECK (flag_reason IN ('not_higher', 'too_slow', 'too_fast')),
    rate_per_day  NUMERIC(9, 1),
    created_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    -- The service must belong to the same vehicle.
    CONSTRAINT odometer_readings_service_same_vehicle_fk
        FOREIGN KEY (service_id, vehicle_id) REFERENCES service_records (id, vehicle_id),
    CONSTRAINT odometer_readings_flagged_has_reason
        CHECK ((status = 'flagged') = (flag_reason IS NOT NULL))
);

-- One 'service' reading per service.
CREATE UNIQUE INDEX odometer_readings_one_per_service_uq ON odometer_readings (service_id)
    WHERE source = 'service';
CREATE INDEX odometer_readings_vehicle_day_idx ON odometer_readings (vehicle_id, reading_date);

-- Backfill: one 'service' reading per existing service, checked against the service before it
-- (same vehicle, by date then id: the order everywhere else in the API).
WITH ordered AS (
    SELECT id, vehicle_id, service_date, odometer_km, engine_hours,
           LAG(service_date) OVER w AS prev_date,
           LAG(odometer_km)  OVER w AS prev_km,
           LAG(engine_hours) OVER w AS prev_hours
    FROM service_records
    WINDOW w AS (PARTITION BY vehicle_id ORDER BY service_date, id)
), valued AS (
    SELECT id, vehicle_id, service_date,
           CASE WHEN odometer_km IS NOT NULL THEN 'km' ELSE 'hours' END AS unit,
           COALESCE(odometer_km::NUMERIC, engine_hours) AS value,
           CASE WHEN odometer_km IS NOT NULL THEN prev_km::NUMERIC ELSE prev_hours END AS prev_value,
           service_date - prev_date AS days
    FROM ordered
), checked AS (
    SELECT *,
           CASE WHEN days > 0 THEN (value - prev_value) / days END AS per_day
    FROM valued
)
INSERT INTO odometer_readings (vehicle_id, service_id, unit, value, reading_date, source, status,
                               flag_reason, rate_per_day)
SELECT vehicle_id, id, unit, value, service_date, 'service',
       CASE WHEN reason IS NULL THEN 'ok' ELSE 'flagged' END, reason, round(per_day, 1)
FROM (
    SELECT *,
           CASE
               WHEN prev_value IS NULL                          THEN NULL
               WHEN value <= prev_value                         THEN 'not_higher'
               WHEN per_day IS NULL                             THEN 'too_fast'   -- higher, same day
               WHEN unit = 'km' AND per_day < 20                THEN 'too_slow'
               WHEN unit = 'km' AND per_day > 1200              THEN 'too_fast'
               WHEN unit = 'hours' AND per_day > 24             THEN 'too_fast'
           END AS reason
    FROM checked
) s
WHERE value IS NOT NULL;

-- ---------------------------------------------------------------- 3. km checks

CREATE TABLE km_checks (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id    BIGINT      NOT NULL REFERENCES vehicles (id),
    -- The vehicle's latest service when the check was sent; one check per service.
    service_id    BIGINT      NOT NULL,
    -- Recipient (driver phone of that service); NULL = there was no phone (asked another way).
    phone         TEXT        CHECK (phone ~ '^[0-9]{8}$'),
    -- The exact text that went out.
    message_text  TEXT        NOT NULL CHECK (btrim(message_text) <> ''),
    channel       TEXT        NOT NULL DEFAULT 'manual' CHECK (channel IN ('manual', 'sms')),
    check_on      DATE        NOT NULL,
    sent_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT km_checks_service_same_vehicle_fk
        FOREIGN KEY (service_id, vehicle_id) REFERENCES service_records (id, vehicle_id),
    CONSTRAINT km_checks_one_per_service_uq UNIQUE (service_id)
);
