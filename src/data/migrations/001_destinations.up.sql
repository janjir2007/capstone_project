-- ---------------------------------------------------------------------
-- destinations: one place a truck can drive to after its oil change.
-- All trips start and end in Ulaanbaatar (synthetic_rules.md §1, ARI ✓ needed).
-- Round-trip km is NOT stored: it is derived (2 × one_way_km, an ESTIMATE
-- in synthetic_rules.md §1) where it is used, so the rule can change without
-- a migration.
-- ---------------------------------------------------------------------
CREATE TABLE destinations (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                  TEXT          NOT NULL UNIQUE CHECK (btrim(name) <> ''),
    -- Same 5 values as service_records.route.
    route_category        TEXT          NOT NULL
                          CHECK (route_category IN ('ub_city', 'mn_china', 'mn_russia', 'mine_site', 'mixed')),
    -- Road km from Ulaanbaatar. NULL = not applicable (ub_city) or not known yet.
    one_way_km            INTEGER       CHECK (one_way_km > 0),
    -- Days for the whole round trip INCLUDING waiting (border, loading), D-035.
    -- NULL until Ari fills them in (synthetic_rules.md §1, TO FILL).
    round_trip_days_min   NUMERIC(5, 1) CHECK (round_trip_days_min > 0),
    round_trip_days_max   NUMERIC(5, 1) CHECK (round_trip_days_max > 0),
    -- Where one_way_km comes from (map link); NULL when there is no km value.
    source                TEXT,
    created_at            TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT destinations_days_min_le_max CHECK (round_trip_days_min <= round_trip_days_max)
);

-- ---------------------------------------------------------------------
-- service_records: destination asked at every service (D-033).
--   destination_id  : the chosen row of destinations (NULL for old records
--                     or when the place is not in the list)
--   destination_raw : what the driver said, when it is not in the list
-- ---------------------------------------------------------------------
ALTER TABLE service_records
    ADD COLUMN destination_id  BIGINT REFERENCES destinations (id),
    ADD COLUMN destination_raw TEXT   CHECK (btrim(destination_raw) <> '');

CREATE INDEX service_records_destination_id_idx ON service_records (destination_id);

