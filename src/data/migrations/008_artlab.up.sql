-- Migration 008 UP — Artlab receipts, bank transfers, sync runs (Task 9.6b-2)
--
-- Read-only copy of what the Artlab sync needs (PM-approved 9.6b plan). Our app never writes
-- to Artlab (D-114). Privacy: NO description text, names, receipt numbers or line items are
-- stored, only the plates + phones found in the text (src/artlab/extract.py).
--
-- 1. artlab_transfers: incoming bank transfers from POST /report/acc-txn («Дансны хуулга»).
--    Filled once Artlab sends an acc-txn sample (src/artlab/transfers.py is a stub until then).
-- 2. artlab_bills: completed sale receipts (SALE_VAT / SALE). Many bills -> one service
--    (no UNIQUE on service_id, PM §4). A bill is linked (service_id + match_confidence) or not
--    (match_note says why). payment_status = the 4 PM statuses:
--    paid «Төлсөн» / unpaid «Төлөөгүй» / paid_later «Төлсөн (дараа)» / unknown «Тодорхойгүй».
--    paid_later always names the transfer that paid it; one transfer pays at most one bill.
-- 3. sync_runs: one row per sync run, counts only (no response bodies).
--
-- plates / phones are arrays: a receipt may hold two phones (driver + owner) or more than
-- one plate; matching (src/artlab/matching.py) needs all of them to re-try later runs.
-- If a service is deleted, its bills become unlinked (ON DELETE SET NULL) and are re-matched.
--
-- Run (the runner provides the transaction):  python -m scripts.migrate
-- Undo: 008_artlab.down.sql
-- =====================================================================

CREATE TABLE artlab_transfers (
    txn_key       TEXT          PRIMARY KEY,           -- Artlab row id, or a hash (transfers.py)
    txn_date      DATE          NOT NULL,
    account_code  TEXT          NOT NULL CHECK (account_code ~ '^[0-9]{1,20}$'),
    amount        NUMERIC(14, 2) NOT NULL,
    plates        TEXT[]        NOT NULL DEFAULT '{}',
    phones        TEXT[]        NOT NULL DEFAULT '{}'
                  CHECK (array_to_string(phones, ',') ~ '^([0-9]{8}(,[0-9]{8})*)?$'),
    synced_at     TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE TABLE artlab_bills (
    artlab_id         BIGINT        PRIMARY KEY,       -- Artlab bill id (num is NOT unique)
    bill_date         DATE          NOT NULL,
    bill_type         TEXT          NOT NULL CHECK (bill_type IN ('SALE_VAT', 'SALE')),
    bill_status       TEXT          NOT NULL CHECK (bill_status = 'COMPLETE'),
    total_gross       NUMERIC(14, 2),                  -- missing on bills without line items
    paid_now          NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (paid_now >= 0),
    credit_amount     NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (credit_amount >= 0),
    plates            TEXT[]        NOT NULL DEFAULT '{}',
    phones            TEXT[]        NOT NULL DEFAULT '{}'
                      CHECK (array_to_string(phones, ',') ~ '^([0-9]{8}(,[0-9]{8})*)?$'),
    service_id        BIGINT        REFERENCES service_records (id) ON DELETE SET NULL,
    match_confidence  TEXT          CHECK (match_confidence IN ('both', 'plate', 'phone')),
    match_note        TEXT          CHECK (match_note IN ('none', 'multiple', 'conflict')),
    payment_status    TEXT          NOT NULL
                      CHECK (payment_status IN ('paid', 'unpaid', 'paid_later', 'unknown')),
    paid_by_txn       TEXT          REFERENCES artlab_transfers (txn_key),
    first_seen_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    synced_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    -- A linked bill says how sure the link is; a note only explains a missing link.
    -- (Not "iff": ON DELETE SET NULL clears service_id but leaves the confidence until re-match.)
    CONSTRAINT artlab_bills_linked_has_confidence CHECK (service_id IS NULL OR match_confidence IS NOT NULL),
    CONSTRAINT artlab_bills_note_only_unlinked CHECK (service_id IS NULL OR match_note IS NULL),
    -- «Төлсөн (дараа)» exactly when a transfer is named; one transfer pays at most one bill.
    CONSTRAINT artlab_bills_paid_later_has_txn CHECK ((payment_status = 'paid_later') = (paid_by_txn IS NOT NULL)),
    CONSTRAINT artlab_bills_one_bill_per_txn UNIQUE (paid_by_txn)
);

CREATE INDEX artlab_bills_service_id_idx ON artlab_bills (service_id);
CREATE INDEX artlab_bills_bill_date_idx ON artlab_bills (bill_date);
-- The unpaid list and the nightly re-check read only these.
CREATE INDEX artlab_bills_unpaid_idx ON artlab_bills (bill_date) WHERE payment_status = 'unpaid';

CREATE TABLE sync_runs (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind            TEXT        NOT NULL CHECK (kind IN ('bills', 'acc_txn', 'nightly')),
    started_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at     TIMESTAMPTZ,
    ok              BOOLEAN,
    bills_seen      INTEGER     NOT NULL DEFAULT 0 CHECK (bills_seen >= 0),
    transfers_seen  INTEGER     NOT NULL DEFAULT 0 CHECK (transfers_seen >= 0),
    error_class     TEXT,                              -- e.g. 'ArtlabError'; never a message body
    CONSTRAINT sync_runs_finished_has_result CHECK (finished_at IS NULL OR ok IS NOT NULL)
);

CREATE INDEX sync_runs_kind_started_idx ON sync_runs (kind, started_at DESC);
